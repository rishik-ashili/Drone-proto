#!/usr/bin/env python3
"""Automated test campaign against the exit criteria of the phase plan.

  P0  hello_square flown 5x in a row, every waypoint reach error < 0.5 m
  P1  landmark detection drives the state machine end to end
  P2  3 consecutive GPS-free landmark missions, return-to-start error logged
  P4  vision correction ON vs OFF (same seeds) - the value of the AI landmarks
  Failsafes: every injected fault produces the expected response

    python scripts/benchmark.py            # full campaign (~10-20 min on a laptop)
    python scripts/benchmark.py --quick    # 1 run per item

Writes docs/benchmark_results.md and logs/benchmark_results.json.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gdnav.navigation.state_machine import State  # noqa: E402
from gdnav.runner import build_sim_runner  # noqa: E402


def fly(mission: str, seed: int, correction: bool = True, faults=None, timeout: float = 400) -> dict:
    r = build_sim_runner(mission, log_path=None, landmark_correction=correction, annotate=False,
                         fault_schedule=faults, seed=seed)
    r.start()
    states = set()
    while r.sm.state not in (State.LANDED, State.ABORTED) and r.t < timeout:
        r.tick()
        states.add(r.sm.state.value)
    s = r.finish()
    s["final_state"] = r.sm.state.value
    s["states_visited"] = sorted(states)
    s["seed"] = seed
    s["events"] = [e for e in r.events if e["type"] in ("state", "fault", "landed", "px4")]
    r.close()
    return s


def fmt(v, d=2):
    return "-" if v is None else (f"{v:.{d}f}" if isinstance(v, float) else str(v))


FAILSAFE_CASES = [
    # name, schedule, expected states/behaviour, check(summary) -> bool
    ("camera_covered", [("camera_covered", 13.5, 4.0)], "hold, resume, mission completes",
     lambda s: "FAILSAFE_HOLD" in s["states_visited"] and s["final_state"] == "LANDED" and s["waypoints_done"] == s["waypoints_total"]),
    ("camera_dropout", [("camera_dropout", 13.5, 3.0)], "hold, resume, mission completes",
     lambda s: "FAILSAFE_HOLD" in s["states_visited"] and s["final_state"] == "LANDED"),
    ("link_loss", [("link_loss", 20.0, 4.0)], "PX4 offboard-loss hold, companion resumes",
     lambda s: any("offboard lost" in e["msg"] for e in s["events"]) and s["final_state"] == "LANDED"),
    ("low_battery", [("low_battery", 20.0, None)], "return to start and land",
     lambda s: "RETURN_TO_START" in s["states_visited"] and s["final_state"] == "LANDED" and s["waypoints_done"] < s["waypoints_total"]),
    ("camera_covered_persistent", [("camera_covered", 13.5, None)], "hold, then land after 10 s",
     lambda s: "FAILSAFE_HOLD" in s["states_visited"] and s["final_state"] == "LANDED" and s["waypoints_done"] == 0),
    ("featureless_floor", [("featureless_floor", 18.0, 8.0)], "survives flow loss (landmarks / hold)",
     lambda s: s["final_state"] == "LANDED"),
    ("false_landmark", [("false_landmark", 5.0, 60.0)], "false detections rejected, mission completes",
     lambda s: s["final_state"] == "LANDED" and s["waypoints_done"] == s["waypoints_total"]),
    ("wind_gust", [("wind_gust", 15.0, 20.0)], "mission completes in 2.9 m/s gusts",
     lambda s: s["final_state"] == "LANDED" and s["collisions"] == 0),
]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    n0, n2, ncmp = (1, 1, 1) if a.quick else (5, 3, 3)
    t0 = time.time()
    res: dict = {}
    md = ["# Benchmark results", "", f"Generated by `scripts/benchmark.py` on {time.strftime('%Y-%m-%d %H:%M')}.", ""]

    print(f"P0: hello_square x{n0}")
    p0 = [fly("hello_square", seed=100 + i) for i in range(n0)]
    ok0 = all(s["final_state"] == "LANDED" and s["reach_error_max_m"] is not None and s["reach_error_max_m"] < 0.5 for s in p0)
    res["P0"] = {"pass": ok0, "runs": p0}
    md += ["## P0 - simulated drone flies the square", "",
           f"Exit criterion: {n0} consecutive runs, every waypoint reach error < 0.5 m. **{'PASS' if ok0 else 'FAIL'}**", "",
           "| run | reach error mean (m) | max (m) | landed |", "|---|---|---|---|"]
    md += [f"| {i + 1} | {fmt(s['reach_error_mean_m'])} | {fmt(s['reach_error_max_m'])} | {s['final_state']} |" for i, s in enumerate(p0)]

    print(f"P1/P2: investor_demo x{n2}")
    p2 = [fly("investor_demo", seed=200 + i) for i in range(n2)]
    ok2 = all(s["final_state"] == "LANDED" and s["landmarks_found"] == s["waypoints_total"] for s in p2)
    res["P2"] = {"pass": ok2, "runs": p2}
    md += ["", "## P1/P2 - GPS-free landmark missions", "",
           f"Exit criterion: {n2} consecutive N-waypoint missions with GNSS disabled; landmark detection drives the state machine; "
           f"return-to-start error logged. **{'PASS' if ok2 else 'FAIL'}**", "",
           "| run | landmarks found | reach err mean (m) | RTS error (m) | RTS % of path | distance (m) | est. err mean (m) | perception (ms) |",
           "|---|---|---|---|---|---|---|---|"]
    md += [f"| {i + 1} | {s['landmarks_found']}/{s['waypoints_total']} | {fmt(s['reach_error_mean_m'])} | {fmt(s.get('rts_error_m'))} | "
           f"{fmt(s.get('rts_error_pct'))} | {fmt(s.get('distance_m'), 1)} | {fmt(s['est_error_mean_m'])} | {fmt(s['perception_ms_mean'], 1)} |"
           for i, s in enumerate(p2)]

    print(f"Vision correction ON vs OFF x{ncmp}")
    cmp_rows = []
    for i in range(ncmp):
        on = p2[i] if i < len(p2) else fly("investor_demo", seed=200 + i)
        off = fly("investor_demo", seed=200 + i, correction=False)
        cmp_rows.append((on, off))
    res["correction"] = [{"on": on, "off": off} for on, off in cmp_rows]
    md += ["", "## Value of AI landmark correction (same seeds)", "",
           "| seed | max estimate error ON (m) | OFF (m) | reach error ON (m) | OFF (m) | RTS error ON (m) | OFF (m) |",
           "|---|---|---|---|---|---|---|"]
    md += [f"| {on['seed']} | {fmt(on['est_error_max_m'])} | {fmt(off['est_error_max_m'])} | {fmt(on['reach_error_mean_m'])} | "
           f"{fmt(off['reach_error_mean_m'])} | {fmt(on.get('rts_error_m'))} | {fmt(off.get('rts_error_m'))} |" for on, off in cmp_rows]

    print("Failsafe matrix")
    md += ["", "## Failsafes (fault injection)", "", "| fault | expected | response | response time (s) | result |",
           "|---|---|---|---|---|"]
    res["failsafes"] = []
    for name, sched, expect, check in FAILSAFE_CASES:
        s = fly("investor_demo", seed=300, faults=sched)
        ok = bool(check(s))
        resp = s["failsafe_responses"][0] if s["failsafe_responses"] else {}
        res["failsafes"].append({"case": name, "pass": ok, "summary": s})
        md.append(f"| {name} | {expect} | {resp.get('response', '-')} | {fmt(resp.get('response_time_s'))} | "
                  f"{'PASS' if ok else 'FAIL'} ({s['final_state']}, {s['waypoints_done']}/{s['waypoints_total']} WPs) |")
        print(f"  {name:28s} {'PASS' if ok else 'FAIL'}")

    md += ["", f"Total wall time: {time.time() - t0:.0f} s. Detector: {p2[0]['detector']}."]
    out_md = ROOT / "docs" / "benchmark_results.md"
    out_md.parent.mkdir(exist_ok=True)
    out_md.write_text("\n".join(md) + "\n")
    (ROOT / "logs").mkdir(exist_ok=True)
    (ROOT / "logs" / "benchmark_results.json").write_text(json.dumps(res, indent=1, default=str))
    print("\n".join(md))
    print(f"\nWritten {out_md}")


if __name__ == "__main__":
    main()
