#!/usr/bin/env python3
"""Export a simulator world to Gazebo (Harmonic) for PX4 SITL.

Writes into gazebo/ (or --out):
  worlds/gdnav_<world>.sdf          arena: textured floor with every landmark, pillars, light
  worlds/materials/<world>_floor.png floor texture (same pixels the built-in simulator renders)
  models/x500_flow_cam_down/        PX4 x500 + optical flow + rangefinder (x500_flow)
                                    + downward camera matching config/sim.yaml (640x480, 80 deg)

Install into PX4 and fly (see docs/GAZEBO.md):
  python scripts/export_gazebo.py --world indoor_arena
  ./scripts/install_gazebo_assets.sh ~/PX4-Autopilot
  cd ~/PX4-Autopilot && PX4_GZ_WORLD=gdnav_indoor_arena PX4_SIM_MODEL=gz_x500_flow_cam_down \\
      make px4_sitl gz_x500_flow

Frames: our worlds are local NED (x north, y east); Gazebo is ENU (x east, y north).
A landmark at NED (n, e) is placed at Gazebo (x=e, y=n). The drone spawns at the origin.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gdnav.common.config import load_sim_config  # noqa: E402
from gdnav.sim.world import World  # noqa: E402

WORLD_SDF = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/export_gazebo.py from worlds/{world}.yaml - do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene>
      <grid>false</grid>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.7 0.7 0.7 1</background>
      <shadows>true</shadows>
    </scene>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{plane_w} {plane_h}</size></plane></geometry>
        </collision>
      </link>
    </model>
    <model name="arena_floor">
      <static>true</static>
      <pose>{floor_x:.3f} {floor_y:.3f} 0.001 0 0 {floor_yaw:.6f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{tex_w:.3f} {tex_h:.3f}</size></plane></geometry>
          <material>
            <diffuse>1 1 1 1</diffuse>
            <specular>0.05 0.05 0.05 1</specular>
            <pbr><metal>
              <albedo_map>materials/{world}_floor.png</albedo_map>
              <roughness>0.9</roughness>
              <metalness>0.0</metalness>
            </metal></pbr>
          </material>
        </visual>
      </link>
    </model>
{obstacles}
    <light name="sun" type="directional">
      <pose>0 0 30 0 0 0</pose>
      <cast_shadows>true</cast_shadows>
      <intensity>1</intensity>
      <direction>0.2 0.3 -0.9</direction>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
    </light>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>47.397971057728974</latitude_deg>
      <longitude_deg>8.546163739800146</longitude_deg>
      <elevation>0</elevation>
    </spherical_coordinates>
  </world>
</sdf>
"""

PILLAR = """    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry></collision>
        <visual name="visual">
          <geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry>
          <material><diffuse>0.42 0.45 0.48 1</diffuse><ambient>0.3 0.3 0.3 1</ambient></material>
        </visual>
      </link>
    </model>"""

MODEL_SDF = """<?xml version="1.0" encoding="UTF-8"?>
<!-- PX4 x500 with optical flow + rangefinder (x500_flow) and a downward camera for the
     landmark detector. Generated by scripts/export_gazebo.py. -->
<sdf version="1.9">
  <model name="x500_flow_cam_down">
    <self_collide>false</self_collide>
    <include merge="true">
      <uri>model://x500_flow</uri>
    </include>
    <link name="down_camera_link">
      <!-- optical axis (+x of the link) pointing down, image top towards the nose -->
      <pose relative_to="base_link">0.05 0 -0.08 0 1.5707963 0</pose>
      <inertial><mass>0.01</mass>
        <inertia><ixx>1e-5</ixx><iyy>1e-5</iyy><izz>1e-5</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <sensor name="down_camera" type="camera">
        <gz_frame_id>down_camera_link</gz_frame_id>
        <topic>{topic}</topic>
        <camera>
          <horizontal_fov>{hfov:.4f}</horizontal_fov>
          <image><width>{w}</width><height>{h}</height><format>R8G8B8</format></image>
          <clip><near>0.05</near><far>50</far></clip>
          <noise><type>gaussian</type><mean>0</mean><stddev>0.007</stddev></noise>
        </camera>
        <always_on>1</always_on>
        <update_rate>{rate}</update_rate>
        <visualize>false</visualize>
      </sensor>
    </link>
    <joint name="down_camera_joint" type="fixed">
      <parent>base_link</parent>
      <child>down_camera_link</child>
    </joint>
  </model>
</sdf>
"""

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>x500_flow_cam_down</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>x500 + optical flow + rangefinder + downward camera (gdnav)</description>
</model>
"""

CAMERA_TOPIC = "/gdnav/down_camera/image"


def export(world_name: str, out: Path) -> None:
    world = World.load(world_name)
    cfg = load_sim_config()
    cam = cfg["sensors"]["camera"]
    (out / "worlds" / "materials").mkdir(parents=True, exist_ok=True)
    tex_path = out / "worlds" / "materials" / f"{world.name}_floor.png"
    tex = world.texture
    if max(tex.shape[:2]) > 4096:  # keep GPU memory reasonable
        s = 4096 / max(tex.shape[:2])
        tex = cv2.resize(tex, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    cv2.imwrite(str(tex_path), tex)

    # NED bounds -> ENU: east extent is Gazebo x, north extent is Gazebo y.
    # The image is north-up, east-right; a Gazebo plane maps image right to +x and image up to +y.
    east_c, north_c = (world.y_min + world.y_max) / 2, (world.x_min + world.x_max) / 2
    obstacles = "\n".join(
        PILLAR.format(name=o.name, x=o.y, y=o.x, z=o.height / 2, r=o.radius, h=o.height) for o in world.obstacles)
    sdf = WORLD_SDF.format(world=world.name, name=f"gdnav_{world.name}", plane_w=200, plane_h=200,
                           floor_x=east_c, floor_y=north_c, floor_yaw=0.0,
                           tex_w=world.y_max - world.y_min, tex_h=world.x_max - world.x_min, obstacles=obstacles)
    (out / "worlds" / f"gdnav_{world.name}.sdf").write_text(sdf)

    mdir = out / "models" / "x500_flow_cam_down"
    mdir.mkdir(parents=True, exist_ok=True)
    (mdir / "model.sdf").write_text(MODEL_SDF.format(topic=CAMERA_TOPIC, hfov=math.radians(cam["hfov_deg"]),
                                                     w=cam["width"], h=cam["height"], rate=30))
    (mdir / "model.config").write_text(MODEL_CONFIG)
    print(f"Wrote {out / 'worlds' / f'gdnav_{world.name}.sdf'}, {tex_path.name}, models/x500_flow_cam_down")
    print("Landmarks (Gazebo ENU x=east, y=north):")
    for lm in world.landmarks:
        print(f"  {lm.name:10s} NED ({lm.x:5.1f}, {lm.y:5.1f})  ->  gz ({lm.y:5.1f}, {lm.x:5.1f})")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--world", default="indoor_arena")
    ap.add_argument("--out", default=str(ROOT / "gazebo"))
    a = ap.parse_args()
    export(a.world, Path(a.out))


if __name__ == "__main__":
    main()
